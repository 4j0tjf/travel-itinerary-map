import dotenv from 'dotenv';
import path from 'node:path';
import { root } from './services/store.js';
import { createApp } from './app.js';
dotenv.config({ path: path.join(root, '.env') });
const port = Number(process.env.PORT || 6001);
const dataDir = path.resolve(root, process.env.DATA_DIR || 'data');
const app = createApp({ dataDir, basePath: process.env.BASE_PATH || '' });
const prune = () => app.locals.routeCache.pruneExpired().catch(() => console.error('Expired route cache cleanup failed.'));
prune();
setInterval(prune, 3600000).unref();
app.listen(port, '0.0.0.0', () => console.log(`Travel API: http://localhost:${port}${process.env.BASE_PATH || ''}`));
